package com.xxxx.emby_tv.util

/**
 * 播放页的直连快进/快退通道。
 *
 * 为什么不能靠方向键：播放页里展开控制条、且没有光点时，左右键是交给焦点系统的，
 * 于是「扳住摇杆快进」到某一刻会变成「焦点在按钮之间一个一个跳」，而且快进会断。
 * 摇杆推住时直接调这里的回调，播放器自己 seek，焦点完全不动。
 *
 * 由 PlayerScreen 在进入时注册、离开时注销；没注册（不在播放页）时调用无副作用。
 */
object PlayerSeekBus {
    /** 参数为毫秒偏移，正数=快进，负数=快退 */
    var seekBy: ((Long) -> Unit)? = null
}
